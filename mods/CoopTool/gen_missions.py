"""Builds freemode_missions.h (the Free Mode missions' fighter lists) from the Urban Reign Coop Tool's data.

    python gen_missions.py <Coop Tool folder>

The Coop Tool (pnach_gen.py) loads missions_original.json (each mission's enemies, from the UR Pnach Editor) and
freemode_missions.json (the 4-player Free Mode cheat's other writes: partner's AI and position...), and fills the 6
enemy records, spreading the copies of the original enemies over the arena. This script takes that result as is.
"""
import os
import sys

ENEMY_TABLE = 0x1DA8654
WORDS = 0xAC // 4


def main():
    folder = os.path.abspath(sys.argv[1])
    sys.path.insert(0, folder)
    import pnach_gen  # noqa: E402  (the Coop Tool's generator, loads its JSON files)

    missions = pnach_gen.MISSIONS
    out = ["// Generated by gen_missions.py from the Urban Reign Coop Tool's mission data: do not edit.",
           "// Each Free Mode mission: its number of enemies, the 4-player cheat's other writes (32 bits), and the 6 enemy",
           "// records (0xAC bytes at 0x1DA8654, sparse: the words left out are 0). Records past the mission's own enemies",
           "// are copies of them, spread over the arena.",
           "#pragma once",
           "#include <cstdint>",
           "",
           "namespace freemode",
           "{",
           "    struct Write",
           "    {",
           "        uint32_t address;",
           "        uint32_t value;",
           "    };",
           "    struct Word",
           "    {",
           "        uint8_t record;",
           "        uint8_t index;",
           "        uint32_t value;",
           "    };",
           "    struct Mission",
           "    {",
           "        uint8_t count;",
           "        uint16_t firstWrite, writes;",
           "        uint16_t firstWord, words;",
           "    };",
           "    constexpr int kRecordWords = %d;" % WORDS,
           ""]
    writes, words, table = [], [], []
    for m in range(1, 101):
        d = missions[m]
        first_write = len(writes)
        for address, value in d["base"]:
            writes.append((address, value & 0xFFFFFFFF))
        first_word = len(words)
        for r, record in enumerate(d["entries"][:6]):
            assert len(record) == WORDS, (m, r, len(record))
            for i, value in enumerate(record):
                if value & 0xFFFFFFFF:
                    words.append((r, i, value & 0xFFFFFFFF))
        table.append((d["count"], first_write, len(writes) - first_write, first_word, len(words) - first_word))
    out.append("    constexpr Write kWrites[] = {")
    for i in range(0, len(writes), 4):
        out.append("        " + " ".join("{0x%07X, 0x%08X}," % w for w in writes[i:i + 4]))
    out.append("    };")
    out.append("    constexpr Word kWords[] = {")
    for i in range(0, len(words), 5):
        out.append("        " + " ".join("{%d, %d, 0x%08X}," % w for w in words[i:i + 5]))
    out.append("    };")
    out.append("    // Missions 1..100 (index = mission - 1).")
    out.append("    constexpr Mission kMissions[] = {")
    for i in range(0, len(table), 4):
        out.append("        " + " ".join("{%d, %d, %d, %d, %d}," % t for t in table[i:i + 4]))
    out.append("    };")
    out.append("}")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "freemode_missions.h")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{path}: {len(writes)} writes, {len(words)} record words")


if __name__ == "__main__":
    main()
